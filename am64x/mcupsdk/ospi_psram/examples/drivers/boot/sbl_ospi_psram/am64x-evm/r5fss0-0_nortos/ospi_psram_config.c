/*
 * Manual OSPI PSRAM configuration.
 *
 * The AM64x has a single physical OSPI0 controller shared by:
 *   - Flash  (CS0, 166.67 MHz) - configured by SysConfig in ti_drivers_config.c
 *   - PSRAM  (CS1, 200 MHz)    - configured manually here
 *
 * To switch between flash and PSRAM:
 *   1. Close OSPI:    Drivers_ospiClose()
 *   2. Swap attrs:    gOspiConfig[CONFIG_OSPI0].attrs = &gOspiAttrs_Psram (or flash)
 *   3. Reopen OSPI:   Drivers_ospiOpen()
 *   4. Toggle switch: i2c_io_expander() for PSRAM, i2c_io_expander_set2flash() for flash
 */

#include "ospi_psram_config.h"
#include <drivers/hw_include/cslr_soc.h>
#include <drivers/sciclient.h>

/*
 * PSRAM OSPI attributes.
 * Key differences from the flash config (generated by SysConfig):
 *   chipSelect  : OSPI_CS1  (PSRAM is on CS1; flash is on CS0)
 *   inputClkFreq: 200 MHz   (vs 166.67 MHz for flash)
 *   baudRateDiv : 8         (200 MHz / 8 = 25 MHz OSPI clock)
 *   dmaEnable   : FALSE     
 *   phyEnable   : FALSE     (no PHY; PHY tuning for PSRAM has not been validated)
 *   dacEnable   : TRUE      
 */
OSPI_Attrs gOspiAttrs_Psram =
{
    .baseAddr             = CSL_FSS0_OSPI0_CTRL_BASE,
    .protocol             = OSPI_PROTO_8D_8D_8D,
    .dataBaseAddr         = CSL_FSS0_DAT_REG1_BASE,
    .moduleId             = TISCI_DEV_FSS0_OSPI_0,
    .clkId                = TISCI_DEV_FSS0_OSPI_0_OSPI_RCLK_CLK,
    .inputClkFreq         = 200000000U,
    .intrNum              = 171U,
    .intrEnable           = FALSE,
    .intrPriority         = 4U,
    .dmaEnable            = FALSE,
    .phyEnable            = FALSE,
    .dacEnable            = TRUE,
    .chipSelect           = OSPI_CS1,
    .frmFmt               = OSPI_FF_POL0_PHA0,
    .decChipSelect        = OSPI_DECODER_SELECT4,
    .baudRateDiv          = 8,
    .dmaRestrictedRegions = NULL,
    .validateOtp          = false,
};
